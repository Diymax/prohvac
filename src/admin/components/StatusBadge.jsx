// Цветная метка состояния: статус перевода, статус заявки, статус доставки
// в Telegram, опубликованность сущности.
//
// ПОЧЕМУ ОДИН КОМПОНЕНТ НА ВСЕ ВИДЫ СТАТУСОВ. Метки в админке отличаются
// только словом и цветом, а поведение у них одно. Пять почти одинаковых
// компонентов означали бы пять мест, где можно забыть title или атрибут
// доступности, и разъехавшуюся палитру между разделами.
//
// Цвет задаёт admin.css по модификатору adm-badge--<status>, поэтому здесь
// нет ни одного inline-стиля: тема админки правится в одном файле.

// Слово, которое видит человек. Ключи совпадают со значениями, которые отдаёт
// сервер, — так метку можно поставить прямо из ответа, ничего не переводя
// в промежуточные «типы» на каждом экране.
const LABELS = {
  // Переводы (server/routes/admin.content.js, statusOf)
  manual: 'вручную',
  machine: 'машинный',
  stale: 'устарел',
  missing: 'нет',

  // Публикация сущностей
  published: 'на сайте',
  hidden: 'скрыт',

  // Заявки
  new: 'новая',
  in_progress: 'в работе',
  done: 'обработана',
  spam: 'спам',

  // Доставка в Telegram
  sent: 'доставлена',
  pending: 'в очереди',
  sending: 'отправляется',
  failed: 'не доставлена',
  delivery_unknown: 'результат неизвестен',
  skipped: 'не отправлялась',
}

// Пояснение к метке. Статус перевода без расшифровки читается неоднозначно:
// «устарел» — это про исходник, который поменяли после перевода, а не про
// возраст текста.
const HINTS = {
  manual: 'Перевод выверен руками — автоперевод его не тронет',
  machine: 'Машинный перевод, руками не правился',
  stale: 'Русский текст изменился после перевода — нужно обновить',
  missing: 'Текста на этом языке ещё нет',
  failed: 'Сообщение в Telegram не ушло — можно отправить повторно',
  pending: 'Сообщение ещё не отправлено в Telegram',
  sending: 'Запрос в Telegram уже выполняется — повторять его нельзя',
  delivery_unknown:
    'Telegram мог принять сообщение, но подтверждение не зафиксировано. Повтор возможен только после проверки чата.',
  skipped: 'Отправка в Telegram была выключена',
}

const StatusBadge = ({ status, label, title, muted = false }) => {
  const code = typeof status === 'string' && status ? status : 'unknown'
  const text = label ?? LABELS[code] ?? code
  const hint = title ?? HINTS[code] ?? ''

  return (
    <span
      className={`adm-badge adm-badge--${code}${muted ? ' adm-badge--muted' : ''}`}
      title={hint || undefined}
    >
      {text}
    </span>
  )
}

export default StatusBadge
