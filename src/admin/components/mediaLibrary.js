// Список загруженных картинок, общий для всех мест, где его показывают.
//
// ПОЧЕМУ КЭШ. Пикер (MediaPicker.jsx) открывается по одному разу на каждое
// поле формы — у проекта это обложка и галерея, — и запрашивать один и тот же
// список на каждое открытие значит дёргать сервер ради ответа, который
// не менялся. Кэш живёт на модуль, то есть на вкладку: сессия админки короткая,
// а библиотека меняется только загрузкой файла из соседнего раздела.
//
// Отдельный файл от компонента нужен ради Fast Refresh: модуль, экспортирующий
// и компонент, и функции, при горячей замене перезагружается целиком и теряет
// состояние соседних экранов.

import { api } from '../api.js'

let cache = null

/**
 * Список файлов медиатеки.
 *
 * @param {{force?: boolean}} [options] force — перечитать, игнорируя кэш
 * @returns {Promise<Array<object>>}
 */
export const loadMediaLibrary = async ({ force = false } = {}) => {
  if (!force && cache) return cache
  const data = await api.get('/api/admin/media')
  cache = Array.isArray(data?.items) ? data.items : []
  return cache
}

/** Сбрасывает кэш. Вызывать после загрузки или удаления файла. */
export const invalidateMediaLibrary = () => {
  cache = null
}

/** Текущее содержимое кэша без запроса: пустой массив, если его ещё нет. */
export const cachedMediaLibrary = () => cache ?? []
