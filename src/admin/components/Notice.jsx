// Строка результата операции: ошибка, успех или пояснение.
//
// ПОЧЕМУ НЕ alert() И НЕ ВСПЛЫВАШКА. Сообщение должно оставаться рядом с тем
// действием, которое его вызвало: «поставлено в очередь 3, устарело 1» имеет
// смысл только возле конкретного ключа, а модальное окно ещё и прерывает
// работу редактора, который правит тексты пачкой.
//
// role='alert' только для ошибок: скринридер обязан прочитать отказ сразу,
// а вежливые сводки об успехе — не перебивая набор текста.

const Notice = ({ kind = 'info', children }) => {
  if (!children) return null

  return (
    <div
      className={`adm-notice adm-notice--${kind}`}
      role={kind === 'error' ? 'alert' : 'status'}
    >
      {children}
    </div>
  )
}

export default Notice
