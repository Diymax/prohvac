// Отдельная точка входа админки.
//
// Лендинг и панель — разные приложения с разными зависимостями: панели
// не нужен ни i18next, ни эффекты на canvas, а лендингу не нужен редактор
// контента. Отдельный вход позволяет собрать их в разные чанки, и посетитель
// сайта не тянет код админки вовсе.
//
// Стили подключает сам AdminApp: дизайн-система панели (adm-*) не должна
// оказаться на странице лендинга даже случайным импортом.

import ReactDOM from 'react-dom/client'

import AdminApp from './AdminApp.jsx'

const container = document.getElementById('root')
// Оболочка одна на весь сайт (server/http/spa.js отдаёт dist/index.html),
// поэтому контейнер тот же самый. Если его нет — значит эту точку входа
// подключили не к той странице, и молчать об этом нельзя: экран останется
// пустым, а причина будет невосстановима.
if (!container) throw new Error('admin: в документе нет #root')

ReactDOM.createRoot(container).render(<AdminApp />)
