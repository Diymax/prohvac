-- 013_metrica_cache.sql — кэш ответов API Яндекс.Метрики.
--
-- ЗАЧЕМ КЭШ. Причин две, и вторая важнее первой.
--
-- 1. Квоты. Stat API допускает до 200 запросов за 5 минут и 5000 в сутки
--    на аккаунт. Экран «Аналитика» делает три запроса на открытие, и без
--    кэша каждое обновление страницы каждым оператором тратило бы квоту.
--
-- 2. Ответ, когда Яндекс недоступен. Токен протух, сеть отвалилась, API
--    отвечает 500 — оператор всё равно должен увидеть последние удачные
--    цифры с честной пометкой «данные от такого-то времени», а не пустой
--    экран с ошибкой. Поэтому строка живёт и ПОСЛЕ истечения expires_at:
--    просроченная запись — это не мусор, это резерв.
--
-- Уборка не по таймеру: строк здесь единицы (ключ = отчёт + период),
-- и каждая перезаписывается при следующем удачном запросе. Расти таблице
-- некуда, отдельная чистка была бы кодом ради нуля строк.
--
-- Сырых данных Метрики тут нет — только агрегаты, которые и так видны
-- в интерфейсе счётчика. ПДн не хранится.
CREATE TABLE IF NOT EXISTS metrica_cache (
  -- '<отчёт>:<период>', например 'summary:30d'. Текстовый ключ, поэтому
  -- WITHOUT ROWID: строка ложится прямо в B-дерево ключа.
  key        TEXT    PRIMARY KEY,
  -- JSON уже разобранного и урезанного ответа, не сырое тело: в кэш кладётся
  -- то, что уходит в браузер, чтобы разбор не повторялся на каждом чтении.
  payload    TEXT    NOT NULL,
  fetched_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL
) STRICT, WITHOUT ROWID;
