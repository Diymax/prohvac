-- 014_telegram_crm.sql — смена статуса заявки прямо из чата Telegram.
--
-- ЗАЧЕМ. Карточка заявки и так приходит менеджеру в чат, а статус до сих пор
-- менялся только в админке: чтобы отметить «взял в работу», надо было открыть
-- панель, войти по паролю и второму фактору, найти заявку. На практике этого
-- не делали, и статусы в панели отражали не работу, а желание её записать.
-- Кнопки под сообщением убирают этот разрыв.
--
-- НОВЫХ СТАТУСОВ НЕТ намеренно. Кнопки в чате раскладываются ровно на те же
-- четыре значения, что уже перечислены в CHECK таблицы leads
-- ('new', 'in_progress', 'done', 'spam'). Это не совпадение, а условие:
-- расширить CHECK в STRICT-таблице SQLite нельзя без полной перестройки
-- таблицы с персональными данными, и ради ярлыка в чате такую операцию
-- проводить незачем. Два источника правды об одном статусе — тоже нет:
-- источник один, меняется он из двух мест.

-- Куда именно ушла карточка. Chat id берётся из настроек, но настройки
-- меняются, а отредактировать сообщение надо в ТОМ чате, где оно лежит:
-- без сохранённого значения после смены chat_id все прежние карточки
-- перестали бы обновляться, причём молча.
ALTER TABLE leads ADD COLUMN telegram_chat_id TEXT;

-- Откуда пришла последняя смена статуса: 'admin' или 'telegram'.
-- NULL — заявка, которой статус не меняли ни разу.
ALTER TABLE leads ADD COLUMN status_source TEXT
  CHECK (status_source IS NULL OR status_source IN ('admin', 'telegram'));

-- Кто изменил, в человекочитаемом виде. Для админки это users.username,
-- для Telegram — @username или имя нажавшего.
--
-- ПОЧЕМУ НЕ ВНЕШНИЙ КЛЮЧ. Нажавший в чате не имеет учётной записи в панели,
-- и связать его не с чем. Строка живёт вместе с заявкой и удаляется вместе
-- с ней по purge_after, поэтому отдельным хранилищем персональных данных
-- не становится.
ALTER TABLE leads ADD COLUMN status_actor TEXT;

ALTER TABLE leads ADD COLUMN status_changed_at INTEGER;

-- Журнал принятых обновлений Telegram — защита от повторной обработки.
--
-- Telegram повторяет доставку обновления, пока не получит 200, и штатно
-- присылает одно и то же по нескольку раз (например, когда наш ответ
-- задержался). Без этой таблицы один и тот же нажатый статус применялся бы
-- дважды и дважды попадал бы в журнал действий.
CREATE TABLE IF NOT EXISTS telegram_updates (
  update_id   INTEGER PRIMARY KEY,
  received_at INTEGER NOT NULL
) STRICT;

-- Уборка по возрасту: update_id растут монотонно, поэтому хватает индекса
-- по времени. Строки — восемь байт полезной нагрузки, но расти таблице
-- незачем, чистит её тот же уборщик, что и заявки.
CREATE INDEX IF NOT EXISTS telegram_updates_received_idx
  ON telegram_updates (received_at);
