// Стартовый файл для Passenger — и единственный CommonJS в проекте.
//
// Passenger грузит точку входа через require(), а проект объявлен
// "type": "module": require() ESM-файла падает с ERR_REQUIRE_ESM ещё до
// первой строки нашего кода, и в логе панели остаётся только эта ошибка,
// без единого намёка на причину. Расширение .cjs заставляет Node прочитать
// файл как CommonJS независимо от package.json, а дальше настоящий сервер
// подключается динамическим import(), который в CJS разрешён.
//
// В панели Plesk «Файл запуска приложения» = app.cjs.

// Passenger не выставляет NODE_ENV сам. Без него server/config.js считает
// окружение development: подставляет дев-заглушки вместо секретов, не требует
// PUBLIC_ORIGIN и не ставит HSTS — то есть боевой сайт молча работает
// в отладочном режиме. ||= не трогает значение, заданное в панели вручную.
process.env.NODE_ENV ||= 'production'

import('./server/index.js').catch((err) => {
  // Ошибка на старте (нет секретов, старый Node без node:sqlite, битая
  // миграция) иначе ушла бы в unhandled rejection — Passenger покажет в панели
  // сам факт падения, но не причину. Печатаем и выходим ненулевым кодом,
  // чтобы процесс не остался висеть без сервера.
  console.error('[boot]', err)
  process.exit(1)
})
